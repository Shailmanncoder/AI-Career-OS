export function heuristicGradeOpenAnswer(answer: string, expectedPoints: string[]) {
  const cleaned = answer.trim();
  if (cleaned.length < 15) {
    return { scorePercent: 0, feedback: "The answer is too short to demonstrate the expected points." };
  }

  const normalizedAnswer = ` ${normalizeSkillKey(cleaned)} `;
  const covered = expectedPoints.filter((point) => {
    const keywords = normalizeSkillKey(point)
      .split(" ")
      .filter((word) => word.length > 4);
    if (keywords.length === 0) return false;
    const hits = keywords.filter((word) => normalizedAnswer.includes(word)).length;
    return hits / keywords.length >= 0.34;
  });

  const coverageRatio = expectedPoints.length > 0 ? covered.length / expectedPoints.length : 0;
  const wordCount = cleaned.split(/\s+/).filter(Boolean).length;
  const depthBonus = Math.min(20, Math.round(wordCount / 6));
  const specificityBonus = /\b\d/.test(cleaned) ? 8 : 0;

  const scorePercent = clamp(Math.round(coverageRatio * 62 + depthBonus + specificityBonus));

  const missed = expectedPoints.filter((point) => !covered.includes(point));
  const feedback =
    missed.length > 0
      ? `Offline grading matched ${covered.length} of ${expectedPoints.length} expected points. Still to address: ${missed.slice(0, 3).join("; ")}.`
      : `Offline grading matched all ${expectedPoints.length} expected points. Add a concrete example with numbers to strengthen it further.`;

  return { scorePercent, feedback };
}

const INTERVIEW_OPENERS: Record<string, string[]> = {
  TECHNICAL: [
    "Walk me through the architecture of the most technically demanding thing you have built. What were the constraints?",
    "Describe a bug that took you more than a day to find. How did you eventually track it down?",
    "How do you decide when a piece of code needs to be refactored rather than extended?",
  ],
  BEHAVIORAL: [
    "Tell me about a time you disagreed with a decision on your team. What did you do?",
    "Describe a project that did not go the way you expected. What would you change?",
    "Tell me about a time you had to learn something unfamiliar under time pressure.",
  ],
  MIXED: [
    "Tell me about a project you are proud of, and walk me through one technical decision you made in it.",
    "Describe a time you had to deliver something with an incomplete specification. How did you proceed?",
    "What is the most useful thing you have learned in the last six months, and how did you apply it?",
  ],
};

export function fallbackInterviewQuestion(context: InterviewContext, askedCount: number) {
  const pool = INTERVIEW_OPENERS[context.kind] ?? INTERVIEW_OPENERS.MIXED;
  const base = pool[askedCount % pool.length];
  if (askedCount === 0) return base;

  const focus = context.focusSkills[(askedCount - 1) % Math.max(1, context.focusSkills.length)];
  if (!focus) return base;
  return `${base.replace(/\?$/, "")} Where relevant, ground your answer in your experience with ${focus}.`;
}

const STRUCTURE_MARKERS = [
  "first",
  "then",
  "next",
  "finally",
  "because",
  "so that",
  "as a result",
  "the problem",
  "my role",
  "the outcome",
];

export function fallbackInterviewEvaluation(
  context: InterviewContext,
  answer: string,
  askedCount: number,
): InterviewEvaluationPayload {
  const cleaned = answer.trim();
  const words = cleaned.split(/\s+/).filter(Boolean);
  const wordCount = words.length;
  const lower = cleaned.toLowerCase();

  const structureHits = STRUCTURE_MARKERS.filter((marker) => lower.includes(marker)).length;
  const skillHits = context.focusSkills.filter((skill) =>
    lower.includes(skill.toLowerCase()),
  ).length;
  const hasNumbers = /\d/.test(cleaned);
  const hasFirstPerson = /\bi\b/.test(lower);

  const completeness = clamp(Math.round(Math.min(100, (wordCount / 140) * 100)));
  const structure = clamp(30 + structureHits * 12 + (hasFirstPerson ? 10 : 0));
  const relevance = clamp(38 + skillHits * 14 + (wordCount > 40 ? 14 : 0));
  const technicalAccuracy = clamp(34 + skillHits * 12 + (hasNumbers ? 12 : 0) + (wordCount > 90 ? 10 : 0));
  const communication = clamp(
    40 + (wordCount > 60 ? 15 : 0) + structureHits * 8 - (wordCount > 420 ? 12 : 0),
  );

  const strengths: string[] = [];
  const improvements: string[] = [];

  if (wordCount >= 90) strengths.push("The answer has enough detail to evaluate.");
  if (structureHits >= 2) strengths.push("The response follows a recognisable narrative structure.");
  if (hasNumbers) strengths.push("Concrete numbers make the impact verifiable.");
  if (skillHits > 0) strengths.push("The answer stays anchored to skills relevant to the role.");
  if (strengths.length === 0) strengths.push("You engaged with the question directly.");

  if (wordCount < 60) improvements.push("Expand the answer: aim for 90 to 180 words with a concrete example.");
  if (structureHits < 2) improvements.push("Use a situation, action, result structure so the listener can follow.");
  if (!hasNumbers) improvements.push("Quantify the outcome, even approximately.");
  if (skillHits === 0 && context.focusSkills.length > 0) {
    improvements.push(`Name the specific technologies involved, such as ${context.focusSkills.slice(0, 2).join(" or ")}.`);
  }
  if (improvements.length === 0) improvements.push("Tighten the opening so the core result lands in the first sentence.");

  return {
    relevance,
    technicalAccuracy,
    structure,
    communication,
    completeness,
    feedback: [
      `Offline evaluation scored this answer on length, structure, specificity, and role relevance.`,
      improvements[0],
      OFFLINE_NOTICE,
    ].join(" "),
    strengths: strengths.slice(0, 4),
    improvements: improvements.slice(0, 4),
    followUpQuestion: fallbackInterviewQuestion(context, askedCount),
  };
}
