export function fallbackRoadmapPlan(context: RoadmapContext): RoadmapPlanPayload {
  const gaps = context.gaps.length > 0 ? context.gaps : [];
  const phaseCount = Math.min(6, Math.max(3, Math.ceil(context.horizonWeeks / 2.5)));
  const weeksPerPhase = Math.max(1, Math.round(context.horizonWeeks / phaseCount));
  const perPhaseHours = Math.max(2, Math.round(context.weeklyHours * weeksPerPhase * 0.4));

  const phases = Array.from({ length: phaseCount }).map((_, phaseIndex) => {
    const template = PHASE_TEMPLATES[Math.min(phaseIndex, PHASE_TEMPLATES.length - 1)];
    const weekStart = Math.min(13, phaseIndex * weeksPerPhase + 1);
    const weekEnd = Math.min(13, Math.max(weekStart, weekStart + weeksPerPhase - 1));
    const isFinal = phaseIndex === phaseCount - 1;
    const assigned = gaps.slice(phaseIndex * 2, phaseIndex * 2 + 2);
    const focusSkill = assigned[0]?.name ?? gaps[phaseIndex % Math.max(1, gaps.length)]?.name;

    const tasks = isFinal
      ? [
          {
            title: "Publish a portfolio write-up for your main project",
            kind: "PROJECT" as const,
            objective: `Document the problem, architecture, and outcome of the project you built for ${context.roleTitle}.`,
            skill: focusSkill,
            estimateHours: Math.min(40, perPhaseHours),
          },
          {
            title: `Rehearse ${context.roleTitle} interview questions`,
            kind: "PRACTICE" as const,
            objective: "Run practice interviews until you can explain every project decision without notes.",
            skill: focusSkill,
            estimateHours: Math.min(40, Math.max(2, Math.round(perPhaseHours * 0.75))),
          },
          {
            title: "Take a skill assessment on your weakest area",
            kind: "ASSESSMENT" as const,
            objective: "Confirm the gap is closed with recorded evidence rather than a resume estimate.",
            skill: gaps[0]?.name,
            estimateHours: 2,
          },
        ]
      : assigned.length > 0
        ? assigned.flatMap((gap) => [
            {
              title: `Study ${gap.name} to level ${gap.requiredLevel}`,
              kind: "LEARN" as const,
              objective: `Move ${gap.name} from an estimated ${gap.currentLevel} toward the ${gap.requiredLevel} this role expects.`,
              skill: gap.name,
              estimateHours: Math.min(40, perPhaseHours),
            },
            {
              title: `Build a small exercise using ${gap.name}`,
              kind: "PRACTICE" as const,
              objective: `Apply ${gap.name} in a scoped exercise so the knowledge survives past the tutorial.`,
              skill: gap.name,
              estimateHours: Math.min(40, Math.max(2, Math.round(perPhaseHours * 0.6))),
            },
          ])
        : [
            {
              title: `Deepen your strongest ${context.roleTitle} skill`,
              kind: "PRACTICE" as const,
              objective: "With no weighted gaps left, convert existing strengths into demonstrable work.",
              skill: context.currentStrengths[0]?.name,
              estimateHours: Math.min(40, perPhaseHours),
            },
          ];

    return {
      title: template.title,
      focus: template.focus,
      weekStart,
      weekEnd,
      tasks: tasks.slice(0, 8),
    };
  });

  return {
    title: `${context.horizonWeeks}-Week Roadmap to ${context.roleTitle}`,
    summary: [
      `A ${context.horizonWeeks} week plan built from your ${gaps.length} recorded skill gaps at ${context.weeklyHours} hours per week.`,
      "Phases are ordered so prerequisite skills come before the skills that build on them.",
      OFFLINE_NOTICE,
    ].join(" "),
    phases,
  };
}

export function fallbackResumeOptimization(
  context: ResumeOptimizerContext,
): ResumeOptimizationPayload {
  const normalizedResume = ` ${normalizeSkillKey(context.resumeText)} `;
  const present = context.roleSkills.filter((skill) =>
    normalizedResume.includes(` ${normalizeSkillKey(skill)} `),
  );
  const missing = context.roleSkills.filter((skill) => !present.includes(skill));
  const keywordCoverage =
    context.roleSkills.length > 0
      ? clamp(Math.round((present.length / context.roleSkills.length) * 100))
      : 0;

  const hasSummary = /\b(summary|profile|objective)\b/i.test(context.resumeText);
  const hasSkillsSection = /\b(skills|technologies|tech stack)\b/i.test(context.resumeText);
  const hasEducation = /\beducation\b/i.test(context.resumeText);
  const hasExperience = /\b(experience|employment)\b/i.test(context.resumeText);
  const hasProjects = /\bprojects?\b/i.test(context.resumeText);

  const sectionsPresent = [hasSummary, hasSkillsSection, hasEducation, hasExperience, hasProjects];
  const sectionCompleteness = clamp(
    Math.round((sectionsPresent.filter(Boolean).length / sectionsPresent.length) * 100),
  );

  const quantified = (context.resumeText.match(/\b\d+(\.\d+)?\s*(%|percent|k\b|m\b|x\b)/gi) ?? []).length;
  const bulletLines = context.resumeText
    .split("\n")
    .filter((line) => /^[-*•]/.test(line.trim()))
    .map((line) => line.replace(/^[-*•]\s*/, "").trim())
    .filter((line) => line.length > 25);

  const formattingWarnings: string[] = [];
  if (/\t/.test(context.resumeText)) {
    formattingWarnings.push("Tab characters were detected, which can misalign text in parsers.");
  }
  if (context.resumeText.split("\n").some((line) => line.length > 220)) {
    formattingWarnings.push("Some lines are very long, which usually indicates multi column layout.");
  }
  if (bulletLines.length < 6) {
    formattingWarnings.push("Fewer than six substantive bullets were found across the document.");
  }
  if (formattingWarnings.length === 0) {
    formattingWarnings.push("No structural formatting problems were detected by the offline parser.");
  }

  const rewrites = bulletLines.slice(0, 4).map((line) => ({
    section: "Experience",
    original: line.slice(0, 600),
    improved: /^[A-Z][a-z]+ed\b/.test(line)
      ? `${line.slice(0, 540)} [add the measurable result, for example time saved or users affected]`
      : `Delivered ${line.charAt(0).toLowerCase()}${line.slice(1, 540)} [add the measurable result]`,
    rationale:
      "Leads with an action verb and reserves an explicit slot for a metric you supply, without inventing one.",
  }));

  return {
    targetAlignmentScore: clamp(Math.round(keywordCoverage * 0.65 + sectionCompleteness * 0.35)),
    atsReadinessScore: clamp(
      Math.round(keywordCoverage * 0.5 + sectionCompleteness * 0.35 + Math.min(15, bulletLines.length)),
    ),
    keywordCoverage,
    sectionCompleteness,
    strengths: [
      present.length > 0
        ? `Your resume already names ${present.length} of the ${context.roleSkills.length} skills this role weights.`
        : "The document parses cleanly, which is the prerequisite for any keyword matching.",
      hasExperience ? "A recognisable experience section is present." : "The document is machine readable.",
      quantified > 0 ? `${quantified} quantified results were detected.` : "Content is concise enough to scan.",
    ],
    weaknesses: [
      missing.length > 0
        ? `${missing.length} weighted skills for this role do not appear anywhere in the text.`
        : "No weighted role skills are missing from the text.",
      hasSummary ? "The summary is present but not tailored to this specific role." : "No summary section was found.",
      quantified < 2 ? "Most bullets describe duties rather than measurable outcomes." : "Impact statements are uneven across roles.",
    ],
    missingKeywords: missing.slice(0, 15),
    formattingWarnings,
    suggestions: [
      {
        section: "Summary",
        issue: hasSummary
          ? "The summary does not name the target role."
          : "There is no summary for a reviewer to anchor on.",
        action: `Open with one line naming ${context.roleTitle} and your two strongest relevant skills.`,
      },
      {
        section: "Skills",
        issue:
          missing.length > 0
            ? `Missing weighted keywords: ${missing.slice(0, 6).join(", ")}.`
            : "The skills section is present and aligned.",
        action:
          missing.length > 0
            ? "Add only the skills you have genuinely used, and back each with a bullet or project."
            : "Keep the skills section ordered by relevance to the target role.",
      },
      {
        section: "Experience",
        issue: "Bullets lead with responsibility rather than outcome.",
        action: "Restructure each bullet as action, method, then result with a number you can defend.",
      },
    ],
    rewrites,
  };
}

